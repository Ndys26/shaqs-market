export const locale = () => (lang === 'ms' ? 'ms-MY' : 'en-MY');

export function setLang(l: Lang) {
  lang = l;
  try { localStorage.setItem(KEY, l); } catch { /* storage blocked */ }
  document.documentElement.lang = locale();
  listeners.forEach((f) => f());
}

/**
 * Translate a key. Text starting with "@" is a stored key (e.g. "@seed.tl.grade"),
 * and any other text (farm notes typed by hand) is shown as it is.
 * Vars starting with "@" are translated too, so stored events stay bilingual.
 */
export function tr(k: Key | string, v?: Vars): string {
  const key = (k.startsWith('@') ? k.slice(1) : k) as Key;
  const raw = DICT[lang][key];
  if (raw === undefined) return k;
  return raw.replace(/\{(\w+)\}/g, (_, n: string) => {
    const x = v?.[n];
    if (x === undefined) return `{${n}}`;
    return typeof x === 'string' && x.startsWith('@') ? tr(x) : String(x);
  });
}

const subscribe = (f: () => void) => { listeners.add(f); return () => { listeners.delete(f); }; };
/** Re-renders the caller when the language changes. */
export const useLang = () => useSyncExternalStore(subscribe, () => lang);

